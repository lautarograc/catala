  # ==========
  # Structures
  # ==========

  # Base class of the structures generated by the Catala compiler. The
  # definition of a structure looks like:
  #
  #   class Person < CatalaRuntime::Struct
  #     struct_name 'Person'
  #     field :birth_date, 'birth_date', :date
  #     field :income, 'income', :money
  #   end
  #
  # and its values are built with keyword arguments:
  # [Person.new(birth_date: ..., income: ...)]
  class Struct
    class << self
      # The original name of the structure in the Catala program
      attr_reader :catala_name

      def struct_name(name)
        @catala_name = name.freeze
      end

      # The list of [field, label, type] of the structure
      def catala_fields
        @catala_fields ||= []
      end

      def field(name, label, type)
        catala_fields << [name, label.freeze, type].freeze
        attr_reader name
      end
    end

    def initialize(**values)
      self.class.catala_fields.each do |name, _label, _type|
        raise ArgumentError, "missing field #{name} for structure #{self.class.catala_name}" unless values.key?(name)

        instance_variable_set(:"@#{name}", values.delete(name))
      end
      raise ArgumentError, "unknown fields #{values.keys.join(', ')} for structure #{self.class.catala_name}" unless values.empty?

      freeze
    end

    # Pairs of field label and value, in declaration order
    def catala_field_values
      self.class.catala_fields.map { |name, label, _type| [label, public_send(name)] }
    end

    def ==(other)
      other.instance_of?(self.class) &&
        self.class.catala_fields.all? { |name, _, _| public_send(name) == other.public_send(name) }
    end
    alias eql? ==

    def hash = [self.class, *self.class.catala_fields.map { |name, _, _| public_send(name) }].hash

    def to_s = CatalaRuntime.format_value(self)
    alias inspect to_s
  end

  # ============
  # Enumerations
  # ============

  # Base class of the enumerations generated by the Catala compiler:
  #
  #   class Status < CatalaRuntime::Enum
  #     enum_name 'Status'
  #     constructor :Single, 'Single', :unit
  #     constructor :Married, 'Married', :date
  #   end
  #
  # Values are built with [Status.new(:Married, date)], and inspected with
  # [#code] and [#payload].
  class Enum
    class << self
      attr_reader :catala_name

      def enum_name(name)
        @catala_name = name.freeze
      end

      # constructor => [index, label, type]
      def constructors
        @constructors ||= {}
      end

      def constructor(name, label, type)
        constructors[name] = [constructors.size, label.freeze, type].freeze
      end
    end

    attr_reader :code, :payload

    def initialize(code, payload = UNIT)
      raise ArgumentError, "unknown constructor #{code} for enumeration #{self.class.catala_name}" unless self.class.constructors.key?(code)

      @code = code
      @payload = payload
      freeze
    end

    def index = self.class.constructors[@code][0]
    def label = self.class.constructors[@code][1]

    def ==(other) = other.instance_of?(self.class) && @code == other.code && @payload == other.payload
    alias eql? ==

    def hash = [self.class, @code, @payload].hash

    def to_s = CatalaRuntime.format_value(self)
    alias inspect to_s
  end

