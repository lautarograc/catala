  # Test runners
  # ============

  # Used by the [run_tests] entry point of the generated programs
  class TestRunner
    def initialize(scopes, options)
      @scopes = scopes
      @options = options
    end

    # Runs the test scope [name] (whose computation is given by the block) if it
    # was selected on the command-line, and prints its result. [trace] is a
    # pair [kind, pos] of the trace node for the scope call, when the program
    # was compiled with tracing.
    def scope(name, trace: nil)
      return unless @scopes.empty? || @scopes.include?(name)

      result =
        if @options[:trace] && trace
          CatalaRuntime.reset_trace
          CatalaRuntime.begin_trace(*trace)
          begin
            r = yield
          rescue Error => e
            CatalaRuntime.error_trace(e)
            puts CatalaRuntime.trace_to_json(CatalaRuntime.retrieve_trace)
            raise
          end
          CatalaRuntime.end_trace(r)
          puts CatalaRuntime.trace_to_json(CatalaRuntime.retrieve_trace)
          r
        else
          yield
        end
      $stderr.puts "\e[32m[RESULT]\e[m Scope #{name} executed successfully."
      return if @options[:test]

      puts(@options[:json] ? CatalaRuntime.to_json(result) : CatalaRuntime.format_value(result))
    end
  end

  # Entry point of the test programs generated by the Catala compiler
  def self.run_tests(argv, lang: :en, description: 'Catala test program')
    options = { test: false, json: false, trace: false }
    parser = OptionParser.new do |o|
      o.banner = "#{description}\nUsage: ruby #{File.basename($PROGRAM_NAME)} [options] [scopes...]"
      o.on('--test', 'check without printing results') { options[:test] = true }
      o.on('--json', 'output results in JSON') { options[:json] = true }
      o.on('--trace', 'output trace in JSON') { options[:trace] = true }
    end
    scopes = parser.parse(argv)
    self.lang = lang
    yield TestRunner.new(scopes, options)
  rescue Error => e
    $stderr.puts "\e[1;31m[ERROR]\e[m #{e.message}"
    exit 1
  end
