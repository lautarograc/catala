  # An amount of money, as an integer number of cents
  class Money
    include Comparable

    attr_reader :cents

    def initialize(cents)
      raise TypeError, "Money expects an integer number of cents, got #{cents.inspect}" unless cents.is_a?(::Integer)

      @cents = cents
      freeze
    end

    # Builds an amount from a number of units (rounded to the nearest cent)
    def self.from_units(units)
      new(CatalaRuntime.round_rational(Rational(units) * 100))
    end

    def +(other) = Money.new(@cents + other.cents)
    def -(other) = Money.new(@cents - other.cents)
    def -@ = Money.new(-@cents)

    # Multiplication by an integer or a decimal, rounded to the nearest cent
    def *(other)
      Money.new(CatalaRuntime.round_rational(Rational(@cents) * other))
    end

    def <=>(other)
      @cents <=> other.cents if other.is_a?(Money)
    end

    def ==(other) = other.is_a?(Money) && @cents == other.cents
    alias eql? ==

    def hash = [Money, @cents].hash

    def zero? = @cents.zero?

    def to_rational = Rational(@cents, 100)

    def to_s = CatalaRuntime.format_value(self)

    def inspect = "#<CatalaRuntime::Money #{@cents} cents>"
  end

  # ==================
  # Dates and periods
  # ==================

  # This is a port of the Dates_calc library (deps/dates-calc), which acts as
  # the reference implementation.
  module Dates
    module_function

    def leap_year?(year)
      (year % 400).zero? || ((year % 4).zero? && !(year % 100).zero?)
    end

    def days_in_month(year, month)
      case month
      when 1, 3, 5, 7, 8, 10, 12 then 31
      when 4, 6, 9, 11 then 30
      when 2 then leap_year?(year) ? 29 : 28
      else raise InvalidDate, "invalid month #{month}"
      end
    end

    def valid?(year, month, day)
      month.between?(1, 12) && day >= 1 && day <= days_in_month(year, month)
    end

    # Returns [year, month] after adding [months] to the given month
    def add_months(year, month, months)
      total = (year * 12) + (month - 1) + months
      [total.div(12), (total % 12) + 1]
    end

    # Number of days since 1970-01-01 (proleptic Gregorian calendar)
    def to_days(year, month, day)
      y = month <= 2 ? year - 1 : year
      era = y.div(400)
      yoe = y - (era * 400)
      doy = (((153 * (month + (month > 2 ? -3 : 9))) + 2) / 5) + day - 1
      doe = (yoe * 365) + (yoe / 4) - (yoe / 100) + doy
      (era * 146_097) + doe - 719_468
    end

    # Inverse of [to_days]
    def of_days(days)
      z = days + 719_468
      era = z.div(146_097)
      doe = z - (era * 146_097)
      yoe = (doe - (doe / 1460) + (doe / 36_524) - (doe / 146_096)) / 365
      y = yoe + (era * 400)
      doy = doe - ((365 * yoe) + (yoe / 4) - (yoe / 100))
      mp = ((5 * doy) + 2) / 153
      d = doy - (((153 * mp) + 2) / 5) + 1
      m = mp + (mp < 10 ? 3 : -9)
      [m <= 2 ? y + 1 : y, m, d]
    end
  end

  # A duration, as a number of years, months and days. These are not
  # normalized: a month has no fixed number of days.
  class Duration
    attr_reader :years, :months, :days

    def initialize(years, months, days)
      @years = years
      @months = months
      @days = days
      freeze
    end

    def to_a = [@years, @months, @days]

    def +(other) = Duration.new(@years + other.years, @months + other.months, @days + other.days)
    def -(other) = Duration.new(@years - other.years, @months - other.months, @days - other.days)
    def -@ = Duration.new(-@years, -@months, -@days)
    def *(other) = Duration.new(@years * other, @months * other, @days * other)

    # The number of days of the duration; fails if it is expressed in months or
    # years
    def to_days
      raise AmbiguousComputation unless @years.zero? && @months.zero?

      @days
    end

    # Structural equality (no unit conversion)
    def ==(other) = other.is_a?(Duration) && to_a == other.to_a
    alias eql? ==

    def hash = [Duration, *to_a].hash

    # Comparison with the semantics of Catala, raising an error if the two
    # durations are not comparable (e.g. months vs. days)
    def compare(other, pos = nil)
      if @days.zero? && other.days.zero?
        ((@years * 12) + @months) <=> ((other.years * 12) + other.months)
      elsif @years.zero? && other.years.zero? && @months.zero? && other.months.zero?
        @days <=> other.days
      else
        raise DateError.new(pos, 'ambiguous comparison between durations in different units (e.g. months vs. days)')
      end
    end

    def equal_to?(other, pos = nil)
      self == other || compare(other, pos).zero?
    end

    def to_s = CatalaRuntime.format_value(self)

    def inspect = "#<CatalaRuntime::Duration #{to_a.inspect}>"
  end

  class Date
    include Comparable

    attr_reader :year, :month, :day

    def initialize(year, month, day)
      raise InvalidDate, format('|%04d-%02d-%02d| is not a valid date', year, month, day) unless Dates.valid?(year, month, day)

      @year = year
      @month = month
      @day = day
      freeze
    end

    def self.of_days(days) = new(*Dates.of_days(days))

    def to_a = [@year, @month, @day]

    def to_days = Dates.to_days(@year, @month, @day)

    def first_day_of_month = Date.new(@year, @month, 1)

    def last_day_of_month = Date.new(@year, @month, Dates.days_in_month(@year, @month))

    # [rounding] is one of :round_up, :round_down, :abort_on_round. Raises
    # AmbiguousComputation if a rounding is required with :abort_on_round.
    def add(duration, rounding = :abort_on_round)
      # Years and months are added at once, so that adding [n] years and [m]
      # months is always equivalent to adding [12n + m] months; only then is the
      # date rounded.
      year, month = Dates.add_months(@year + duration.years, @month, duration.months)
      date =
        if Dates.valid?(year, month, @day)
          Date.new(year, month, @day)
        else
          case rounding
          when :round_down then Date.new(year, month, Dates.days_in_month(year, month))
          when :round_up then Date.new(*Dates.add_months(year, month, 1), 1)
          else raise AmbiguousComputation
          end
        end
      duration.days.zero? ? date : Date.of_days(date.to_days + duration.days)
    end

    # Date difference, as a number of days
    def -(other) = Duration.new(0, 0, to_days - other.to_days)

    def <=>(other)
      to_a <=> other.to_a if other.is_a?(Date)
    end

    def ==(other) = other.is_a?(Date) && to_a == other.to_a
    alias eql? ==

    def hash = [Date, *to_a].hash

    def to_s = CatalaRuntime.format_value(self)

    def inspect = "#<CatalaRuntime::Date #{format('%04d-%02d-%02d', @year, @month, @day)}>"
  end

