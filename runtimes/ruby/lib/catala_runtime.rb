  module Trace
    # Base class for the kinds of trace nodes
    class Kind
      def self.kind = raise(NotImplementedError)

      def payload = nil

      def to_json(*_args)
        p = payload
        p.nil? ? %({"kind":#{JSON.generate(self.class.kind)}}) : %({"kind":#{JSON.generate(self.class.kind)},#{p}})
      end
    end

    class VarDef
      attr_reader :name, :decl_pos

      def initialize(name, decl_pos)
        @name = name
        @decl_pos = decl_pos
      end

      def appendable_json = %("name":#{JSON.generate(@name)},"decl_pos":#{@decl_pos.to_json})
    end

    class ScopeCall < Kind
      def self.kind = 'scope_call'

      def initialize(name, decl_pos)
        super()
        @var_def = VarDef.new(name, decl_pos)
      end

      def payload = @var_def.appendable_json
    end

    class ScopeVarDef < Kind
      def self.kind = 'scope_var'

      # [io_input] is one of :no_input, :only_input, :reentrant
      def initialize(name, decl_pos, io_input, output)
        super()
        @var_def = VarDef.new(name, decl_pos)
        @io_input = io_input
        @output = output
      end

      def payload
        %(#{@var_def.appendable_json},"input":#{JSON.generate(@io_input.to_s)},"output":#{@output ? 'true' : 'false'})
      end
    end

    class LocalVarDef < Kind
      def self.kind = 'local_var'

      def initialize(name, decl_pos)
        super()
        @var_def = VarDef.new(name, decl_pos)
      end

      def payload = @var_def.appendable_json
    end

    class LocalTupDef < Kind
      def self.kind = 'local_tup'

      def initialize(var_defs)
        super()
        @var_defs = var_defs
      end

      def payload = %("names":[#{@var_defs.map { |v| "{#{v.appendable_json}}" }.join(',')}])
    end

    class FunCall < Kind
      def self.kind = 'function_call'

      def initialize(name, decl_pos)
        super()
        @var_def = VarDef.new(name, decl_pos)
      end

      def payload = @var_def.appendable_json
    end

    class BranchingCondition < Kind
      def self.kind = 'branch_condition'
    end

    class IfBranching < Kind
      def self.kind = 'if_branching'
    end

    class Assertion < Kind
      def self.kind = 'assertion'
    end

    class MatchBranching < Kind
      def self.kind = 'match_branching'

      def initialize(constructor)
        super()
        @constructor = constructor
      end

      def payload = %("constructor":#{JSON.generate(@constructor)})
    end

    class ExceptionTrace < Kind
      def self.kind = 'exception'

      def initialize(label, label_pos, cons_pos)
        super()
        @label = label
        @label_pos = label_pos
        @cons_pos = cons_pos
      end

      def payload
        p = +''
        p << %("label":#{JSON.generate(@label)},"pos":#{@label_pos.to_json},) unless @label.nil? || @label_pos.nil?
        p << %("cons_pos":#{@cons_pos.to_json})
      end
    end

    class ErrorTrace < Kind
      def self.kind = 'error'

      def initialize(error, related_pos = [])
        super()
        @error = error
        @related_pos = related_pos
      end

      # Same format as the OCaml runtime
      def payload
        type = @error.class.name.split('::').last
        type = "#{type}(#{@error.note.inspect})" if @error.is_a?(DateError)
        related = @related_pos.empty? ? '' : %(,"related_pos":[#{@related_pos.map(&:to_json).join(',')}])
        message = @error.note || @error.description
        %("type":#{JSON.generate(type)}#{related},"message":#{JSON.generate(message)})
      end
    end

    class Node
      attr_reader :kind, :pos, :parent, :sub_nodes
      attr_accessor :value

      def initialize(kind, pos, parent)
        @kind = kind
        @pos = pos
        @parent = parent
        @value = nil
        @sub_nodes = nil
      end

      def add_sub_node(node)
        (@sub_nodes ||= []) << node
      end

      def to_json(*_args)
        v = @value.nil? ? '' : %(,"value":#{CatalaRuntime.to_json(@value)})
        sub = @sub_nodes.nil? ? '' : %(,"trace":[#{@sub_nodes.map(&:to_json).join(',')}])
        %({"element":#{@kind.to_json},"pos":#{@pos.to_json}#{v}#{sub}})
      end
    end

    class Context
      attr_reader :root_nodes

      def initialize
        @current_node = nil
        @root_nodes = []
      end

      def begin_trace(kind, pos)
        node = Node.new(kind, pos, @current_node)
        if @current_node.nil?
          @root_nodes << node
        else
          @current_node.add_sub_node(node)
        end
        @current_node = node
      end

      def end_trace(value = nil)
        return if @current_node.nil?

        @current_node.value = value
        @current_node = @current_node.parent
      end

      def single_trace(kind, pos)
        begin_trace(kind, pos)
        end_trace
      end

      def error_trace(err)
        positions = err.source_positions
        raise err if positions.empty?

        single_trace(ErrorTrace.new(err, positions.drop(1)), positions[0])
      end
    end
  end

  @trace_context = Trace::Context.new

  def self.begin_trace(kind, pos) = @trace_context.begin_trace(kind, pos)
  def self.end_trace(value = nil) = @trace_context.end_trace(value)
  def self.error_trace(err) = @trace_context.error_trace(err)
  def self.reset_trace = (@trace_context = Trace::Context.new)
  def self.retrieve_trace = @trace_context.root_nodes
  def self.trace_to_json(trace) = "[#{trace.map(&:to_json).join(',')}]"

