  # ==================
  # Printing languages
  # ==================

  LANGS = %i[en fr pl].freeze

  @lang = :en
  @max_decimals = 6

  class << self
    attr_reader :lang, :max_decimals

    def lang=(lang)
      raise ArgumentError, "unknown language #{lang.inspect}" unless LANGS.include?(lang)

      @lang = lang
    end

    def max_decimals=(n)
      raise ArgumentError, 'the number of decimals must be positive' unless n.is_a?(::Integer) && n.positive?

      @max_decimals = n
    end
  end

  def self.translate(en:, fr:, pl:)
    case @lang
    when :fr then fr
    when :pl then pl
    else en
    end
  end

