# The Ruby runtime for the code generated by the Catala compiler.
#
# This file should be kept in sync with the reference OCaml runtime
# (runtimes/ocaml/catala_runtime.ml), which defines the semantics of all the
# operations implemented here.
#
# Catala values are represented as follows:
#
#   Catala type        Ruby representation
#   -----------        -------------------
#   integer            ::Integer
#   decimal            ::Rational
#   boolean            true / false
#   money              CatalaRuntime::Money (integer number of cents)
#   date               CatalaRuntime::Date
#   duration           CatalaRuntime::Duration
#   list of t          ::Array
#   (t1, t2)           CatalaRuntime::Tuple
#   optional of t      CatalaRuntime::Option
#   structures         subclasses of CatalaRuntime::Struct
#   enumerations       subclasses of CatalaRuntime::Enum
#   external types     subclasses of CatalaRuntime::Value
#   functions          anything that responds to #call (Proc, Method)
#   code_location      CatalaRuntime::SourcePosition
#   ()                 CatalaRuntime::UNIT

require 'json'
require 'optparse'

module CatalaRuntime
