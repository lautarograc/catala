  # ===============
  # Rounding helper
  # ===============

  # Rounds to the nearest integer, half away from zero
  def self.round_rational(q)
    q.round(half: :up)
  end

  # Integer division truncating towards zero (Ruby's [/] rounds towards
  # negative infinity)
  def self.truncated_div(a, b)
    q = a.abs / b.abs
    (a.negative? ^ b.negative?) ? -q : q
  end

