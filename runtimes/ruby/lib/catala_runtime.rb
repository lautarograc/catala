  class SourcePosition
    attr_reader :filename, :start_line, :start_column, :end_line, :end_column, :law_headings

    def initialize(filename, start_line, start_column, end_line, end_column, law_headings = [])
      @filename = filename
      @start_line = start_line
      @start_column = start_column
      @end_line = end_line
      @end_column = end_column
      @law_headings = law_headings.freeze
      freeze
    end

    def to_a
      [@filename, @start_line, @start_column, @end_line, @end_column]
    end

    def ==(other)
      other.is_a?(SourcePosition) && to_a == other.to_a
    end
    alias eql? ==

    def hash
      to_a.hash
    end

    def <=>(other)
      to_a <=> other.to_a if other.is_a?(SourcePosition)
    end

    def to_s
      "#{@filename}:#{@start_line}.#{@start_column}-#{@end_line}.#{@end_column}"
    end
    alias inspect to_s

    def to_json(*_args)
      JSON.generate(
        { 'file' => @filename,
          'start' => { 'line' => @start_line, 'character' => @start_column },
          'end' => { 'line' => @end_line, 'character' => @end_column } }
      )
    end
  end

  # ======
  # Errors
  # ======

  # Base class of the errors raised by the evaluation of Catala programs. All
  # errors carry the source positions they relate to, and an optional note.
  class Error < StandardError
    attr_reader :source_positions, :note

    def self.description
      'unspecified error'
    end

    def initialize(source_positions = nil, note = nil)
      @source_positions =
        case source_positions
        when nil then []
        when ::Array then source_positions
        else [source_positions]
        end
      @note = note
      super(build_message)
    end

    def description
      self.class.description
    end

    private

    def build_message
      msg = "At #{@source_positions.map(&:to_s).join(', ')}: #{description}"
      msg += ". #{@note}" unless @note.nil?
      msg
    end
  end

  class AssertionFailed < Error
    def self.description = "an assertion doesn't hold"
  end

  class NoValue < Error
    def self.description = 'no applicable rule to define this variable in this situation'
  end

  class Conflict < Error
    def self.description = 'conflict between multiple valid consequences for assigning the same variable'
  end

  class DivisionByZero < Error
    def self.description = 'a value is being used as denominator in a division and it computed to zero'
  end

  class ListEmpty < Error
    def self.description = 'the list was empty'
  end

  class NotSameLength < Error
    def self.description = 'traversing multiple lists of different lengths'
  end

  class UncomparableValues < Error
    def self.description = 'attempting to compare values with uncomparable types'
  end

  # The message of date errors is the note itself
  class DateError < Error
    def self.description = 'date error'

    def description
      @note || super
    end

    private

    def build_message
      "At #{@source_positions.map(&:to_s).join(', ')}: #{description}"
    end
  end

  class Impossible < Error
    def self.description = '"impossible" computation reached'
  end

