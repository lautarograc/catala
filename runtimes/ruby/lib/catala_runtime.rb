  # Base class for the implementation of the abstract types of external modules.
  # It wraps a value; subclasses may refine the printing, comparison or JSON
  # conversion.
  class Value
    include Comparable

    attr_reader :value

    def initialize(value)
      @value = value
      freeze
    end

    def self.from_json(str, pos = nil)
      from_json_value(CatalaRuntime.parse_json(str, pos), pos)
    end

    def self.from_json_value(value, _pos = nil)
      new(value)
    end

    def <=>(other)
      @value <=> other.value if other.instance_of?(self.class)
    end

    def ==(other) = other.instance_of?(self.class) && @value == other.value
    alias eql? ==

    def hash = [self.class, @value].hash

    def to_s = @value.to_s

    def to_json(*args) = @value.to_json(*args)
  end

