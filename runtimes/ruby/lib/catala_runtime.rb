  # Debugging
  # =========

  def self.debug_print(label, value)
    $stderr.puts "#{label} = #{format_value(value)}"
    value
  end

  # ========
  # Printing
  # ========

  def self.format_integer(n)
    sep = translate(en: ',', fr: ' ', pl: ',')
    digits = n.abs.to_s
    groups = []
    groups.unshift(digits.slice!(-3, 3)) while digits.length > 3
    groups.unshift(digits)
    (n.negative? ? '-' : '') + groups.join(sep)
  end

  def self.format_decimal(r)
    r = Rational(r)
    den = r.denominator
    int_part, rem = r.numerator.abs.divmod(den)
    bigsep = translate(en: ',', fr: ' ', pl: ',')
    out = +(r.negative? ? '-' : '')
    out << format_integer(int_part)
    ndigit = 0
    loop do
      n, rem = (rem * 10).divmod(den)
      out << (ndigit.zero? ? translate(en: '.', fr: ',', pl: '.') : bigsep) if (ndigit % 3).zero?
      out << n.to_s
      break unless rem.positive?

      if ndigit + 1 >= @max_decimals
        out << '…'
        break
      end
      ndigit += 1
    end
    out
  end

  def self.format_money(m)
    units, cents = m.cents.abs.divmod(100)
    (m.cents.negative? ? '-' : '') +
      translate(en: '$', fr: '', pl: '') +
      format_integer(units) +
      translate(en: '.', fr: ',', pl: '.') +
      format('%02d', cents) +
      translate(en: '', fr: ' €', pl: ' PLN')
  end

  def self.format_duration(d)
    splur = ->(n, s) { n.abs > 1 ? [n, "#{s}s"] : [n, s] }
    items =
      case @lang
      when :fr then [splur.(d.years, 'an'), [d.months, 'mois'], splur.(d.days, 'jour')]
      when :pl then [[d.years, 'rok'], [d.months, 'miesiac'], [d.days, 'dzien']]
      else [splur.(d.years, 'year'), splur.(d.months, 'month'), splur.(d.days, 'day')]
      end
    # Drop the leading zeroes, but keep at least one item; then drop the other
    # zero items
    items = items.drop(1) while items.length > 1 && items[0][0].zero?
    items = [items[0]] + items.drop(1).reject { |n, _| n.zero? }
    "[#{items.map { |n, s| "#{n} #{s}" }.join(', ')}]"
  end

  # Formats a value like the other Catala backends do
  def self.format_value(v, indent = 0)
    nl = ->(n) { "\n#{' ' * (indent + n)}" }
    case v
    when true then translate(en: 'true', fr: 'vrai', pl: 'prawda')
    when false then translate(en: 'false', fr: 'faux', pl: 'falsz')
    when ::Integer then format_integer(v)
    when ::Rational then format_decimal(v)
    when Money then format_money(v)
    when Date then format('|%04d-%02d-%02d|', v.year, v.month, v.day)
    when Duration then format_duration(v)
    when Unit then '()'
    when ::Array
      return '[]' if v.empty?

      "[#{v.map { |x| "#{nl.(2)}#{format_value(x, indent + 2)};" }.join}#{nl.(0)}]"
    when Tuple then "(#{v.map { |x| format_value(x, indent + 1) }.join(', ')})"
    when Struct
      fields = v.catala_field_values
      return "#{v.class.catala_name} {}" if fields.empty?

      "#{v.class.catala_name} {#{fields.map { |l, x| "#{nl.(2)}-- #{l}: #{format_value(x, indent + 2)}" }.join}#{nl.(0)}}"
    when Enum
      return v.label if v.payload.is_a?(Unit)

      "#{v.label} #{translate(en: 'content', fr: 'contenu', pl: 'typu')} #{format_value(v.payload, indent + 2)}"
    when Option
      if v.none?
        translate(en: 'Absent', fr: 'Absent', pl: 'Nieobecny')
      else
        "#{translate(en: 'Present', fr: 'Présent', pl: 'Obecny')} " \
          "#{translate(en: 'content', fr: 'contenu', pl: 'typu')} #{format_value(v.value, indent + 2)}"
      end
    when Proc, Method then '<function>'
    else v.to_s
    end
  end

  # ====
  # JSON
  # ====

  def self.to_json(v)
    case v
    when true, false then v.to_s
    when ::Integer then %("#{v}")
    when ::Rational then v.denominator == 1 ? %("#{v.numerator}") : %("#{v.numerator}/#{v.denominator}")
    when Money
      units, cents = v.cents.abs.divmod(100)
      %("#{v.cents.negative? ? '-' : ''}#{units}.#{format('%02d', cents)}")
    when Date then format('"%04d-%02d-%02d"', v.year, v.month, v.day)
    when Duration then %({"years":#{v.years},"months":#{v.months},"days":#{v.days}})
    when Unit then '{}'
    when ::Array, Tuple then "[#{v.map { |x| to_json(x) }.join(',')}]"
    when Struct then "{#{v.catala_field_values.map { |l, x| "#{JSON.generate(l)}:#{to_json(x)}" }.join(',')}}"
    when Enum then "{#{JSON.generate(v.label)}:#{to_json(v.payload)}}"
    when Option then v.none? ? '"Absent"' : %({"Present":#{to_json(v.value)}})
    when Proc, Method then '"<function>"'
    when SourcePosition then v.to_json
    else
      v.respond_to?(:to_json) ? v.to_json : JSON.generate(v.to_s)
    end
  end

  def self.parse_json(str, pos = nil)
    JSON.parse(str)
  rescue JSON::ParserError => e
    raise AssertionFailed.new(pos, "invalid JSON value: #{e.message}")
  end

  # Decodes a JSON string into a value of the given type. Types are described
  # by symbols for the base types (e.g. [:integer]), arrays for the
  # parametrised types (e.g. [[:array, :integer]]) and classes for the
  # structures, enumerations and external types.
  def self.from_json(type, str, pos = nil)
    return type.from_json(str, pos) if type.is_a?(Class) && type <= Value

    of_json_value(type, parse_json(str, pos), pos)
  end

  def self.of_json_value(type, v, pos = nil)
    fail_decode = -> { raise AssertionFailed.new(pos, "can't decode #{v.inspect} as a value of type #{type.inspect}") }
    case type
    when :integer
      v.is_a?(::Integer) || (v.is_a?(String) && v.match?(/\A-?\d+\z/)) ? Integer(v) : fail_decode.()
    when :decimal
      begin
        Rational(v.is_a?(Float) ? v.to_s : v)
      rescue ArgumentError, TypeError
        fail_decode.()
      end
    when :money
      begin
        Money.from_units(Rational(v.is_a?(Float) ? v.to_s : v))
      rescue ArgumentError, TypeError
        fail_decode.()
      end
    when :bool then [true, false].include?(v) ? v : fail_decode.()
    when :unit then UNIT
    when :date
      m = v.is_a?(String) && v.match(/\A(\d{4})-(\d{2})-(\d{2})\z/)
      fail_decode.() unless m
      begin
        Date.new(m[1].to_i, m[2].to_i, m[3].to_i)
      rescue InvalidDate
        fail_decode.()
      end
    when :duration
      fail_decode.() unless v.is_a?(Hash)
      Duration.new(v.fetch('years', 0), v.fetch('months', 0), v.fetch('days', 0))
    when :any, :function, :position then fail_decode.()
    when ::Array
      kind, *params = type
      case kind
      when :array
        v.is_a?(::Array) ? v.map { |x| of_json_value(params[0], x, pos) } : fail_decode.()
      when :tuple
        v.is_a?(::Array) && v.length == params.length ? Tuple.new(*params.zip(v).map { |t, x| of_json_value(t, x, pos) }) : fail_decode.()
      when :option
        if v == 'Absent' then Option::NONE
        elsif v.is_a?(Hash) && v.key?('Present') then Option.some(of_json_value(params[0], v['Present'], pos))
        else fail_decode.()
        end
      else fail_decode.()
      end
    when Class
      if type <= Value
        type.from_json_value(v, pos)
      elsif type <= Struct
        fail_decode.() unless v.is_a?(Hash)
        type.new(**type.catala_fields.to_h { |name, label, t| [name, of_json_value(t, v.fetch(label) { fail_decode.() }, pos)] })
      elsif type <= Enum
        label, payload = v.is_a?(String) ? [v, nil] : (v.is_a?(Hash) && v.size == 1 ? v.first : fail_decode.())
        code, (_, _, t) = type.constructors.find { |_, (_, l, _)| l == label } || fail_decode.()
        type.new(code, t == :unit ? UNIT : of_json_value(t, payload, pos))
      else fail_decode.()
      end
    else fail_decode.()
    end
  end

