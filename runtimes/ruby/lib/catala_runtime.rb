  # =========
  # Divisions
  # =========

  def self.div_int_int(a, b, pos = nil)
    raise DivisionByZero, pos if b.zero?

    Rational(a, b)
  end

  def self.div_rat_rat(a, b, pos = nil)
    raise DivisionByZero, pos if b.zero?

    a / b
  end

  def self.div_mon_mon(a, b, pos = nil)
    raise DivisionByZero, pos if b.zero?

    Rational(a.cents, b.cents)
  end

  def self.div_mon_rat(m, r, pos = nil)
    raise DivisionByZero, pos if r.zero?

    m * (1 / Rational(r))
  end

  def self.div_mon_int(m, i, pos = nil) = div_mon_rat(m, Rational(i), pos)

  def self.div_dur_dur(a, b, pos = nil)
    days_a, days_b =
      begin
        [a.to_days, b.to_days]
      rescue AmbiguousComputation
        raise DateError.new(pos, 'dividing durations that are not in days')
      end
    div_int_int(days_a, days_b, pos)
  end

  # ===============
  # Date operations
  # ===============

  def self.add_date_duration(date, duration, rounding = :abort_on_round, pos = nil)
    date.add(duration, rounding)
  rescue AmbiguousComputation
    raise DateError.new(pos, 'ambiguous date computation with no rounding mode specified')
  end

  def self.sub_date_duration(date, duration, rounding = :abort_on_round, pos = nil)
    add_date_duration(date, -duration, rounding, pos)
  end

  # ======================
  # Equality and ordering
  # ======================

  def self.equal_values(a, b, pos = nil)
    case a
    when Duration then b.is_a?(Duration) && a.equal_to?(b, pos)
    when ::Array
      b.is_a?(::Array) && a.length == b.length &&
        a.each_index.all? { |i| equal_values(a[i], b[i], pos) }
    when Tuple
      b.is_a?(Tuple) && a.size == b.size &&
        a.elements.each_index.all? { |i| equal_values(a[i], b[i], pos) }
    when Struct
      b.instance_of?(a.class) &&
        a.class.catala_fields.all? { |name, _, _| equal_values(a.public_send(name), b.public_send(name), pos) }
    when Enum
      b.instance_of?(a.class) && a.code == b.code && equal_values(a.payload, b.payload, pos)
    when Option
      b.is_a?(Option) && (a.none? ? b.none? : b.some? && equal_values(a.value, b.value, pos))
    when Proc, Method then raise UncomparableValues, pos
    else a == b
    end
  end

  def self.compare_lists(l1, l2, pos)
    l1.each_index do |i|
      return 1 if i >= l2.length

      c = compare_values(l1[i], l2[i], pos)
      return c unless c.zero?
    end
    l1.length < l2.length ? -1 : 0
  end

  # Returns -1, 0 or 1
  def self.compare_values(a, b, pos = nil)
    c =
      case a
      when true, false
        raise UncomparableValues, pos unless [true, false].include?(b)

        (a ? 1 : 0) <=> (b ? 1 : 0)
      when Duration then a.compare(b, pos)
      when ::Array then compare_lists(a, b, pos)
      when Tuple then compare_lists(a.to_a, b.to_a, pos)
      when Struct
        c = a.class.catala_name <=> b.class.catala_name
        c = compare_lists(a.catala_field_values.map(&:last), b.catala_field_values.map(&:last), pos) if c.zero?
        c
      when Enum
        c = a.class.catala_name <=> b.class.catala_name
        c = a.index <=> b.index if c.zero?
        c = compare_values(a.payload, b.payload, pos) if c.zero?
        c
      when Option
        if a.none? then b.none? ? 0 : -1
        elsif b.none? then 1
        else compare_values(a.value, b.value, pos)
        end
      when Proc, Method then raise UncomparableValues, pos
      else a <=> b
      end
    raise UncomparableValues, pos if c.nil?

    c
  end

  def self.eq(a, b, pos = nil) = equal_values(a, b, pos)
  def self.lt(a, b, pos = nil) = compare_values(a, b, pos).negative?
  def self.lte(a, b, pos = nil) = compare_values(a, b, pos) <= 0
  def self.gt(a, b, pos = nil) = compare_values(a, b, pos).positive?
  def self.gte(a, b, pos = nil) = compare_values(a, b, pos) >= 0

  # ===============
  # List operations
  # ===============

  # Applies a function value. When the program is compiled with closure
  # conversion, function values are pairs of a function and its environment,
  # which is passed as first argument.
  def self.apply(f, *args)
    f.is_a?(Tuple) ? f[0].call(f[1], *args) : f.call(*args)
  end

  def self.map(f, list) = list.map { |x| apply(f, x) }

  def self.map2(f, list1, list2, pos = nil)
    raise NotSameLength, pos unless list1.length == list2.length

    list1.each_index.map { |i| apply(f, list1[i], list2[i]) }
  end

  def self.filter(f, list) = list.select { |x| apply(f, x) }

  def self.fold(f, init, list) = list.reduce(init) { |acc, x| apply(f, acc, x) }

  def self.reduce(f, list)
    return Option::NONE if list.empty?

    Option.some(list.drop(1).reduce(list[0]) { |acc, x| apply(f, acc, x) })
  end

  def self.find(f, list)
    i = list.index { |x| apply(f, x) }
    i.nil? ? Option::NONE : Option.some(list[i])
  end

  # Stable sort by the given key
  def self.sort_asc(f, list, pos = nil)
    keys = list.map { |x| apply(f, x) }
    list.each_index.sort { |i, j| compare_values(keys[i], keys[j], pos).nonzero? || (i <=> j) }.map { |i| list[i] }
  end

  def self.sort_desc(f, list, pos = nil)
    keys = list.map { |x| apply(f, x) }
    list.each_index.sort { |i, j| compare_values(keys[j], keys[i], pos).nonzero? || (i <=> j) }.map { |i| list[i] }
  end

  # ========
  # Defaults
  # ========

  # Takes a list of optional pairs (value, position), and returns the only
  # present one, if any. Raises a Conflict if more than one is present.
  def self.handle_exceptions(exceptions)
    active = exceptions.select(&:some?)
    case active.length
    when 0 then Option::NONE
    when 1 then active[0]
    else raise Conflict, active.map { |e| e.value[1] }
    end
  end

