open Clerk_utils
open Catala_utils

let catala_flags_ruby = Var.make_vector "CATALA_FLAGS_RUBY"
let ruby = Var.make_scalar "RUBY"

module Spec : Sig.Spec = struct
  open Var
  open File
  module Nj = Ninja_utils

  let name = "ruby"
  let src_extensions = ["rb"]
  let module_extensions = ["rb"]
  let obj_extension = "rb"
  let all_obj_extensions = ["rb"]
  let stdlib_subdir = ""

  let var_defs
      ~config
      ~autotest
      ~use_default_flags
      ~test_flags
      ~include_dirs:_
      ~trace =
    let catala_flags =
      Flags.catala_backend_flags ~autotest ~use_default_flags ~test_flags
        ~accepts_closure_conversion:true ~trace
    in
    let def v x = Var.def ~overrides:config.Clerk_cli.file.variables v x in
    [def catala_flags_ruby catala_flags; def ruby (lazy "ruby")]

  let[@ocamlformat "disable"] rules =
    [
      Nj.rule "catala-ruby"
        ~command:[!!catala_exe; Nj.Expr.Word name; !!catala_flags; !!catala_flags_ruby;
                  !!catala_includes;
                  Nj.Expr.Word "-o"; !!output; Nj.Expr.Word "--"; !!input]
        ~description:[Nj.Expr.Word "<catala>"; Nj.Expr.Word name; Nj.Expr.Word "⇒"; !!output];
    ]

  let build_runtime ~config:_ ~stdbase =
    let ruby_base = stdbase / name / "catala_runtime" in
    let ruby_src = !runtime / name / "lib" in
    [
      Nj.build "phony"
        ~inputs:[Nj.Expr.Word (ruby_base -.- "rb"); !!catala_exe]
        ~outputs:
          [Nj.Expr.Word "@ruby/runtime/src"; Nj.Expr.Word "@ruby/runtime/obj"];
      Nj.build "copy"
        ~inputs:[Nj.Expr.Word (ruby_src / "catala_runtime.rb")]
        ~outputs:[Nj.Expr.Word (ruby_base -.- "rb")];
    ]

  let catala ?vars ~is_stdlib:_ ~inputs ~implicit_in ~has_scope_tests:_ =
    Seq.return
      (Nj.build "catala-ruby" ?vars ~inputs ~implicit_in
         ~outputs:[Common.target ~name "rb"])

  let build_object _ = Seq.empty

  let runtime_dir : File.t Lazy.t =
    lazy File.(Lazy.force Poll.runtime_dir / name / "lib")

  (* An entry point requiring all the modules of the target *)
  let write_target_def_file ~config:_ ~info:_ ~dir target =
    let open File in
    File.with_out_channel
      (dir / (String.to_id target.Clerk_config.tname ^ "_target.rb"))
      (fun oc ->
        Printf.fprintf oc
          "# Generated by clerk: loads all the modules of target %s\n\n"
          target.Clerk_config.tname;
        List.iter
          (fun m -> Printf.fprintf oc "require_relative %S\n" m)
          target.Clerk_config.tmodules)

  let install_target ~config ~info target =
    Common.install_target_files ~name ~stdlib_subdir ~extensions:src_extensions
      ~config ~info target.Clerk_config.tname target ~copy_in:File.copy_in;
    write_target_def_file ~config ~info
      ~dir:(config.Clerk_cli.file.global.target_dir / name / target.tname)
      target

  let install_runtime ~config =
    let open File in
    let dir = config.Clerk_cli.file.global.target_dir / name / Scan.libcatala in
    remove dir;
    ensure_dir dir;
    copy_dir ()
      ~filter:(fun f -> Filename.check_suffix f ".rb")
      ~src:(Lazy.force runtime_dir) ~dst:dir

  let write_project_def ~config ~info:_ =
    File.(
      with_out_channel
        (config.Clerk_cli.file.global.target_dir / name / "Gemfile"))
    @@ fun oc ->
    output_string oc "# Generated by clerk\n\n";
    output_string oc "source 'https://rubygems.org'\n";
    List.iter
      (fun l -> Printf.fprintf oc "gem %S\n" l)
      config.Clerk_cli.file.backends_conf.ruby.use_libs

  let linking_command ~build_dir ~var_bindings:_ link_deps item target =
    (* a "linked" ruby module is a "Module" folder containing the module .rb
       file along with all its dependencies. The runtime is found through the
       load path. *)
    let open File in
    let tdir = Filename.remove_extension target in
    remove tdir;
    ensure_dir tdir;
    List.iter
      (fun it ->
        let src =
          let f = Scan.target_file_name it in
          (build_dir / dirname f / "ruby" / basename f) ^ ".rb"
        in
        copy_in ~src ~dir:tdir)
      (link_deps item);
    copy_in ~src:(target -.- "rb") ~dir:tdir;
    []

  let run_artifact ~config ~var_bindings ~test ~trace ?scope ?quiet src =
    let open File in
    let build_dir = config.Clerk_cli.file.global.build_dir in
    let script = File.remove_extension src / Filename.basename src in
    let cmd =
      Var.get var_bindings ruby
      @ ["-I"; build_dir / Scan.libcatala / "ruby"; script]
      @ Option.to_list scope
      @ (if test && not Global.options.debug then ["--test"] else [])
      @ (if Global.options.output_format = JSON then ["--json"] else [])
      @ if trace then ["--trace"] else []
    in
    Message.debug "Executing artifact: '%s'..." (String.concat " " cmd);
    Clerk_cli.run_command_line ?quiet cmd
end

include Common.Make_backend (Spec)
